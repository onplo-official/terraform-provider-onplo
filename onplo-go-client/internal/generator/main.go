// Command generator writes Onplo's Go client from the outsiders' OpenAPI documents in
// api-contracts/. `go generate ./...` in the module runs it; its output is never committed
// (decision 0548).
//
// WHICH DOCUMENTS. A document is taken when its one `servers` address is the outsiders' door.
// A door for our own apps is served under /our-frontend/ (decision 0813, rule 5) and is left out
// by that same field, so a per-screen read never reaches a published program. A new outsiders'
// contract is in the client the day its document lands, with nothing to change here: the list of
// domains has one home, and it is the folder tree (the npm SDK's generate.mjs follows the same rule).
//
// WHAT IT WRITES, under -out:
//
//	<package>/client.gen.go       the typed client and models for one document, by oapi-codegen
//	operations/operations.gen.go  every operation as data, which the command line reads
package main

import (
	"flag"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/util"
)

const banner = "// Code generated by onplo.com/go-client/internal/generator from api-contracts/; DO NOT EDIT.\n\n"

// document is one outsiders' OpenAPI document, loaded.
type document struct {
	Domain  string // the folder under api-contracts/, for example "account"
	Package string // the Go package it is written as
	File    string // its path, for messages
	Server  string
	Spec    *openapi3.T
}

type loader func(path string) (*openapi3.T, error)

func main() {
	contracts := flag.String("contracts", "../../api-contracts", "the api-contracts folder")
	out := flag.String("out", "generated", "the folder to write the client into")
	flag.Parse()
	if err := run(*contracts, *out); err != nil {
		fmt.Fprintln(os.Stderr, "generator:", err)
		os.Exit(1)
	}
}

func run(contracts, out string) error {
	docs, err := outsidersDocuments(contracts, util.LoadSwagger)
	if err != nil {
		return err
	}
	if len(docs) == 0 {
		return fmt.Errorf("no outsiders' OpenAPI document under %s: refusing to write an empty client", contracts)
	}
	if err := os.RemoveAll(out); err != nil {
		return err
	}
	// THE TABLE IS READ FIRST, because oapi-codegen rewrites the document it is given: it
	// capitalises every operationId in place (readThing becomes ReadThing), and the command line's
	// names are the contract's ids, not the generator's.
	table, err := operationsFile(docs)
	if err != nil {
		return err
	}
	if err := write(filepath.Join(out, "operations", "operations.gen.go"), table); err != nil {
		return err
	}
	for _, d := range docs {
		nameInlineTypes(d.Spec)
		code, err := typedClient(d)
		if err == nil {
			err = declaredOnce(code)
		}
		if err != nil {
			return fmt.Errorf("%s: %w", d.File, err)
		}
		if err := write(filepath.Join(out, d.Package, "client.gen.go"), []byte(code)); err != nil {
			return err
		}
	}
	return nil
}

func write(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, content, 0o644)
}

// outsidersDocuments loads every document in <root>/<domain>/openapi/ and keeps the outsiders' ones.
func outsidersDocuments(root string, load loader) ([]document, error) {
	files, err := filepath.Glob(filepath.Join(root, "*", "openapi", "*.yaml"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	var docs []document
	packages := map[string]string{}
	for _, file := range files {
		spec, err := load(file)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		server, err := serverOf(spec)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		if isOurFrontend(server) {
			continue
		}
		domain := filepath.Base(filepath.Dir(filepath.Dir(file)))
		pkg := packageName(domain, strings.TrimSuffix(filepath.Base(file), ".yaml"))
		if other, taken := packages[pkg]; taken {
			return nil, fmt.Errorf("%s and %s would both be written as package %q", other, file, pkg)
		}
		packages[pkg] = file
		docs = append(docs, document{Domain: domain, Package: pkg, File: file, Server: server, Spec: spec})
	}
	return docs, nil
}

// serverOf is the one absolute https address a contract names. A client that guessed would call nowhere.
func serverOf(spec *openapi3.T) (string, error) {
	if len(spec.Servers) != 1 || spec.Servers[0] == nil {
		return "", fmt.Errorf("names %d server addresses; a contract names exactly one", len(spec.Servers))
	}
	address := spec.Servers[0].URL
	u, err := url.Parse(address)
	if err != nil || u.Scheme != "https" || u.Host == "" || strings.Contains(address, "{") {
		return "", fmt.Errorf("server %q is not an absolute https address", address)
	}
	return strings.TrimSuffix(address, "/"), nil
}

func isOurFrontend(server string) bool {
	u, _ := url.Parse(server)
	return strings.HasPrefix(u.Path+"/", "/our-frontend/")
}

var notLetterOrDigit = regexp.MustCompile(`[^a-z0-9]`)

// packageName is the domain, or the domain and the file's name when a domain has two outsiders' documents.
func packageName(domain, base string) string {
	name := domain
	if base != domain {
		name = domain + base
	}
	return notLetterOrDigit.ReplaceAllString(strings.ToLower(name), "")
}

func typedClient(d document) (string, error) {
	// TWO SCHEMAS MAY BECOME ONE GO NAME. A contract names a component and an inline answer the
	// same way more than once (Account's PurchaseAskAnswer, the first proof run), and oapi-codegen
	// stops at the first. It renames the later ones instead, so the client follows the contract
	// as written and no contract carries a Go-only annotation.
	cfg := codegen.Configuration{
		PackageName:   d.Package,
		Generate:      codegen.GenerateOptions{Client: true, Models: true},
		OutputOptions: codegen.OutputOptions{ResolveTypeNameCollisions: true},
		// EVERY ENUM CONSTANT CARRIES ITS TYPE'S NAME. Unprefixed, an engagement that is "client"
		// became the constant Client, the client type's own name (the proof run of ONPLO-5160).
		Compatibility: codegen.CompatibilityOptions{AlwaysPrefixEnumValues: true},
	}
	cfg = cfg.UpdateDefaults()
	if err := cfg.Validate(); err != nil {
		return "", err
	}
	return codegen.Generate(d.Spec, cfg)
}
